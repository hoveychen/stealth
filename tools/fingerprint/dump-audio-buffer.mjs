// Regenerates src/browser/webapi/audio/chrome_audio*.bin and chrome_audio.zig
// from real Chrome, on both platforms this engine can claim to be.
//
//   node tools/fingerprint/dump-audio-buffer.mjs [--headed]
//
// G10 established that the canonical audio fingerprint cannot be computed --
// it is a function of the host's FFT and libm, not of the spec -- so the only
// way to answer a detector with a real number is to record one. macOS comes
// from the Chrome installed here; Linux comes from the official amd64 package
// in a container (see linux-chrome.mjs, which explains why emulation is safe
// for this particular measurement).
//
// This writes raw little-endian f32 rather than Zig float literals: the tail
// sum a detector hashes moves with a single ULP, and a decimal round-trip
// through source text is exactly the kind of place a ULP goes missing.
import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Cdp, sleep } from './cdp.mjs';
import { withLinuxChrome } from './linux-chrome.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const outDir = path.join(repo, 'src/browser/webapi/audio');
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const headed = process.argv.includes('--headed');
const FRAMES = 5000;
const SAMPLE_RATE = 44100;

// The graph every fingerprintjs clone builds. Kept as one string so both
// engines are asked exactly the same question.
const PROBE = `(async () => {
  const ctx = new OfflineAudioContext(1, ${FRAMES}, ${SAMPLE_RATE});
  const osc = ctx.createOscillator();
  osc.type = 'triangle';
  osc.frequency.value = 10000;
  const comp = ctx.createDynamicsCompressor();
  comp.threshold.value = -50;
  comp.knee.value = 40;
  comp.ratio.value = 12;
  comp.attack.value = 0;
  comp.release.value = 0.25;
  osc.connect(comp);
  comp.connect(ctx.destination);
  osc.start(0);
  const d = (await ctx.startRendering()).getChannelData(0);
  let sum = 0;
  for (let i = 4500; i < ${FRAMES}; i++) sum += Math.abs(d[i]);
  let lead = 0;
  while (lead < d.length && d[lead] === 0) lead++;
  const bytes = new Uint8Array(d.buffer, d.byteOffset, d.byteLength);
  let s = '';
  for (let i = 0; i < bytes.length; i++) s += String.fromCharCode(bytes[i]);
  return JSON.stringify({ ua: navigator.userAgent, tailSum: String(sum), leadingZeros: lead, b64: btoa(s) });
})()`;

async function measure(endpoint) {
  const cdp = await Cdp.connect(endpoint);
  try {
    const { targetId } = await cdp.send('Target.createTarget', { url: 'about:blank' });
    const { sessionId } = await cdp.send('Target.attachToTarget', { targetId, flatten: true });
    const res = await cdp.send('Runtime.evaluate', { expression: PROBE, awaitPromise: true, returnByValue: true }, sessionId);
    if (res.exceptionDetails) throw new Error(res.exceptionDetails.exception?.description ?? res.exceptionDetails.text);
    return JSON.parse(res.result.value);
  } finally {
    cdp.close();
  }
}

// --- macOS: the Chrome installed on this machine ------------------------------
const PORT = 9463;
const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'dump-audio-'));
const flags = [`--remote-debugging-port=${PORT}`, `--user-data-dir=${tmp}`, '--no-first-run', '--no-default-browser-check'];
if (!headed) flags.push('--headless=new');
const chrome = spawn(CHROME, flags, { stdio: ['ignore', 'pipe', 'pipe'] });
chrome.stdout.resume();
chrome.stderr.resume();
for (let i = 0; i < 200; i++) {
  try {
    await (await fetch(`http://127.0.0.1:${PORT}/json/version`)).json();
    break;
  } catch {
    await sleep(200);
  }
}
let macos;
try {
  macos = await measure(`http://127.0.0.1:${PORT}`);
} finally {
  chrome.kill('SIGKILL');
  await fs.rm(tmp, { recursive: true, force: true }).catch(() => {});
}
console.log(`macos  tailSum=${macos.tailSum} leadingZeros=${macos.leadingZeros}`);

// --- Linux: the official amd64 package, in a container ------------------------
const linux = await withLinuxChrome(async (endpoint, version) => {
  console.log(`linux  container is ${version.Browser}`);
  return measure(endpoint);
});
console.log(`linux  tailSum=${linux.tailSum} leadingZeros=${linux.leadingZeros}`);

for (const [name, r] of [['macos', macos], ['linux', linux]]) {
  const buf = Buffer.from(r.b64, 'base64');
  if (buf.length !== FRAMES * 4) throw new Error(`${name}: expected ${FRAMES * 4} bytes, got ${buf.length}`);
  await fs.writeFile(path.join(outDir, `chrome_audio_${name}.bin`), buf);
}

const zig = `// GENERATED by tools/fingerprint/dump-audio-buffer.mjs — do not hand-edit.
//
// The canonical audio fingerprint, recorded rather than computed. G10 (see
// tools/fingerprint/README.md) established that this render cannot be derived:
// the wavetable comes from 36 inverse FFTs backed by vDSP on macOS and PFFFT
// everywhere else, and the compressor's inner loop calls the platform's libm
// per sample. There is no "Chrome" answer, only one answer per platform, so
// G21 stores what each platform actually produced.
//
// The graph, which is what every fingerprintjs clone builds:
//   OfflineAudioContext(1, frames, ${SAMPLE_RATE})
//   OscillatorNode  type=triangle  frequency=10000  start(0)
//     -> DynamicsCompressorNode  threshold=-50 knee=40 ratio=12 attack=0 release=0.25
//       -> destination
//
// Two facts measured alongside the buffers make one stored table enough:
//   * a 44100-frame render is frame-for-frame identical to a ${FRAMES}-frame one
//     over the frames they share, so any length a detector picks is a prefix;
//   * the first ${macos.leadingZeros} samples are exactly zero -- the compressor's 6 ms pre-delay.
//
// Recorded from:
//   macos  ${macos.ua}
//          tail sum over frames 4500..${FRAMES} = ${macos.tailSum}
//   linux  ${linux.ua}
//          tail sum over frames 4500..${FRAMES} = ${linux.tailSum}
//
// The bytes are little-endian f32, which is the only layout either recorded
// platform uses.

pub const Platform = enum { macos, linux };

pub const sample_rate: f64 = ${SAMPLE_RATE};
pub const frames: usize = ${FRAMES};

const macos_bytes align(4) = @embedFile("chrome_audio_macos.bin").*;
const linux_bytes align(4) = @embedFile("chrome_audio_linux.bin").*;

/// The recorded render for one platform, as the destination channel data.
pub fn samples(platform: Platform) *const [frames]f32 {
    return switch (platform) {
        .macos => @ptrCast(&macos_bytes),
        .linux => @ptrCast(&linux_bytes),
    };
}
`;

await fs.writeFile(path.join(outDir, 'chrome_audio.zig'), zig);
console.log(`wrote ${outDir}/chrome_audio{.zig,_macos.bin,_linux.bin}`);
