// Regenerates src/browser/webapi/speech/voices.zig from the real Chrome on this
// machine. speechSynthesis.getVoices() is a strong fingerprint surface — an
// empty list is the headless tell — so the table has to be measured, not
// invented, exactly like tools/fingerprint's other reference data.
//
//   node tools/fingerprint/dump-voices.mjs [--headed]
//
// getVoices() fills in asynchronously on first load, so this polls until the
// list stops growing rather than reading it once.
import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { personaScaleFlags } from './cdp.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const headed = process.argv.includes('--headed');
const PORT = 9462;
const outPath = path.join(repo, 'src/browser/webapi/speech/voices.zig');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const PROBE = `(async () => {
  const ss = speechSynthesis;
  // Two phases: wait for the list to arrive at all (it is empty for the first
  // few hundred ms after load), then wait for it to stop growing.
  let voices = ss.getVoices();
  for (let i = 0; i < 40 && voices.length === 0; i++) {
    await new Promise((r) => setTimeout(r, 250));
    voices = ss.getVoices();
  }
  for (let i = 0, prev = -1; i < 20 && voices.length !== prev; i++) {
    prev = voices.length;
    await new Promise((r) => setTimeout(r, 250));
    voices = ss.getVoices();
  }
  return JSON.stringify({
    version: navigator.userAgent,
    voices: voices.map((v) => ({ voiceURI: v.voiceURI, name: v.name, lang: v.lang, localService: v.localService, default: v.default })),
  });
})()`;

const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'dump-voices-'));
const flags = [`--remote-debugging-port=${PORT}`, `--user-data-dir=${tmp}`, '--no-first-run', '--no-default-browser-check', ...personaScaleFlags()];
if (!headed) flags.push('--headless=new');
// CDP_ENDPOINT points this at a Chrome we did not spawn -- the Linux container
// from linux-chrome.mjs. The claim is macOS, so the table that belongs in the
// tree is the local Chrome's (run with --headed: a headless one fills the list
// too late), and the container is now only useful for reading what the other
// claim would have to carry -- 19 remote voices and no local ones.
const ENDPOINT = process.env.CDP_ENDPOINT ?? null;
const proc = ENDPOINT ? null : spawn(CHROME, flags, { stdio: ['ignore', 'pipe', 'pipe'] });
proc?.stdout.resume();
proc?.stderr.resume();

const pending = new Map();
let id = 1, ws;
const send = (method, params, sessionId) =>
    new Promise((resolve, reject) => {
        const i = id++;
        pending.set(i, { resolve, reject });
        ws.send(JSON.stringify({ id: i, method, params, sessionId }));
        setTimeout(() => { if (pending.delete(i)) reject(new Error(`timeout ${method}`)); }, 60000);
    });

const zigString = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

try {
    let ver = null;
    for (let i = 0; i < 100; i++) { try { ver = await (await fetch(`${ENDPOINT ?? `http://127.0.0.1:${PORT}`}/json/version`)).json(); break; } catch { await sleep(200); } }
    if (!ver) throw new Error('Chrome CDP never came up');
    ws = new WebSocket(ver.webSocketDebuggerUrl);
    await new Promise((res, rej) => { ws.addEventListener('open', res); ws.addEventListener('error', rej); });
    ws.addEventListener('message', (ev) => {
        const m = JSON.parse(ev.data);
        if (m.id && pending.has(m.id)) { const { resolve, reject } = pending.get(m.id); pending.delete(m.id); m.error ? reject(new Error(m.error.message)) : resolve(m.result); }
    });
    const { targetId } = await send('Target.createTarget', { url: 'https://example.com/' });
    const { sessionId } = await send('Target.attachToTarget', { targetId, flatten: true });
    await send('Runtime.enable', {}, sessionId);
    await sleep(1500);
    const r = await send('Runtime.evaluate', { expression: PROBE, returnByValue: true, awaitPromise: true }, sessionId);
    if (r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails).slice(0, 500));
    const { version, voices } = JSON.parse(r.result.value);
    if (voices.length === 0) throw new Error('Chrome reported no voices — refusing to write an empty table');

    const lines = [
        '// GENERATED by tools/fingerprint/dump-voices.mjs — do not hand-edit.',
        '//',
        `// Measured from ${version}`,
        `// ${voices.length} voices, ${new Set(voices.map((v) => v.lang)).size} distinct languages.`,
        '//',
        '// This is the macOS system voice list as Chrome reports it. An empty',
        '// getVoices() is a headless tell (CreepJS renders it as "local (0):',
        '// blocked"), so the list is carried verbatim rather than approximated.',
        '',
        'const Voice = @import("SpeechSynthesisVoice.zig");',
        '',
        'pub const all = [_]Voice{',
    ];
    for (const v of voices) {
        lines.push(`    .{ ._voice_uri = ${zigString(v.voiceURI)}, ._name = ${zigString(v.name)}, ._lang = ${zigString(v.lang)}, ._local_service = ${v.localService}, ._default = ${v.default} },`);
    }
    lines.push('};', '');
    await fs.mkdir(path.dirname(outPath), { recursive: true });
    await fs.writeFile(outPath, lines.join('\n'));
    console.log(`wrote ${path.relative(repo, outPath)} — ${voices.length} voices`);
} finally {
    try { ws && ws.close(); } catch {}
    proc?.kill('SIGKILL');
    await fs.rm(tmp, { recursive: true, force: true }).catch(() => {});
}
