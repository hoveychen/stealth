// Regenerates src/browser/js/global_order.zig from the Chrome capture.
//
//   node tools/fingerprint/gen-global-order.mjs
//
// The order in which a global's own properties were created is readable from
// script and is uploaded verbatim by at least one guard, so the engine installs
// its names in Chrome's order rather than in whatever order its own type list
// happens to be in. This turns the captured list into the comptime table that
// drives that. Edit the capture (results/chrome-global-order.json) and rerun --
// hand-editing the .zig file is reverted the next time anyone regenerates.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../..');
const ref = JSON.parse(fs.readFileSync(path.join(HERE, 'results/chrome-global-order.json'), 'utf8'));

const body = ref.names.map((n) => `    "${n}",`).join('\n');
const out = `// GENERATED by tools/fingerprint/gen-global-order.mjs -- do not edit by hand.
//
// The order Chrome ${ref.chrome} creates its global's own properties in, captured
// ${ref.captured}. ${ref.names.length} names.
//
// Property creation order is observable (\`Object.getOwnPropertyNames(window)\`
// returns it) and DataDome's device-check uploads the whole sequence inside its
// encrypted payload, so this is a fingerprint surface like any other reading.
// Every name this engine exposes on the window global is in this list, so a
// rank lookup that misses is a name we have and Chrome does not -- worth a
// compile error rather than a silent append.
//
// Regenerate from tools/fingerprint/results/chrome-global-order.json.
const std = @import("std");

pub const names = [_][]const u8{
${body}
};

/// Chrome's position for \`name\`, or null if Chrome has no such global.
pub fn rank(comptime name: []const u8) ?usize {
    comptime {
        // One linear scan of ${ref.names.length} names, several hundred times over
        // (once per global this engine defines), all at comptime.
        @setEvalBranchQuota(names.len * 8);
        for (names, 0..) |n, i| {
            if (std.mem.eql(u8, n, name)) return i;
        }
        return null;
    }
}

/// Chrome's position for \`name\`; a compile error if Chrome has no such global,
/// which is how a name only this engine has gets caught at build time.
pub fn rankOrFail(comptime name: []const u8) usize {
    comptime {
        return rank(name) orelse @compileError(
            "global '" ++ name ++ "' is not in Chrome's global order table. " ++
                "Either Chrome does not expose it -- in which case neither should we -- " ++
                "or the capture in tools/fingerprint/results/chrome-global-order.json is stale; " ++
                "recapture with tools/fingerprint/global-order.mjs and rerun gen-global-order.mjs.",
        );
    }
}
`;

const dest = path.join(REPO, 'src/browser/js/global_order.zig');
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(REPO, dest)} (${ref.names.length} names)`);
