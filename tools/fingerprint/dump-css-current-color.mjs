// Regenerates src/browser/webapi/css/chrome_current_color.zig from the real
// Chrome on this machine: which longhands follow the element's own `color`
// rather than a fixed initial value.
//
//   node tools/fingerprint/dump-css-current-color.mjs [--headed]
//
// `chrome_initial_values.zig` records one value per longhand, measured on an
// element that declares nothing -- and on that element `color` is black, so
// every longhand whose real initial value is `currentcolor` was recorded as
// `rgb(0, 0, 0)`. That is right exactly while the page leaves the text black.
// Measured on Chrome 151: an element carrying `color:red` answers
// `rgb(255, 0, 0)` for `border-top-color`, `outline-color`,
// `text-decoration-color`, `caret-color`, `column-rule-color` and
// `text-emphasis-color`, where this engine answered black for all six.
//
// The set is measured rather than listed, and measured twice with different
// colours: a longhand is in it only when it tracks *both*, which rules out a
// name that merely happens to have `rgb(1, 2, 3)` as its initial value.
import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Cdp, newPage, goto, evaluate, sleep, personaScaleFlags } from './cdp.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const CHROME = process.env.CHROME ||
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const PORT = Number(process.env.PORT ?? 9479);
const outPath = path.join(repo, 'src/browser/webapi/css/chrome_current_color.zig');
const headed = process.argv.includes('--headed');

const PAGE = 'data:text/html,' + encodeURIComponent(
    '<!doctype html><title>currentcolor</title><meta name="color-scheme" content="light">' +
    '<body><div id=a></div><div id=b></div>');

const PROBE = `(() => {
  const a = document.getElementById('a');
  const b = document.getElementById('b');
  a.setAttribute('style', 'color:rgb(1, 2, 3)');
  b.setAttribute('style', 'color:rgb(4, 5, 6)');

  const csA = getComputedStyle(a);
  const csB = getComputedStyle(b);
  const names = [];
  for (let i = 0; i < csA.length; i++) names.push(csA[i]);

  // A longhand follows the element's colour when it answers each colour in
  // turn. \`color\` itself is excluded: it is the source, not a follower.
  const follows = names.filter((n) => n !== 'color' &&
    csA.getPropertyValue(n) === 'rgb(1, 2, 3)' &&
    csB.getPropertyValue(n) === 'rgb(4, 5, 6)');

  return JSON.stringify({ ua: navigator.userAgent, total: names.length, follows });
})()`;

const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'lp-currentcolor-'));
const args = [
    `--remote-debugging-port=${PORT}`, `--user-data-dir=${tmp}`,
    '--no-first-run', '--no-default-browser-check', ...personaScaleFlags(), '--force-color-profile=srgb',
];
if (!headed) args.push('--headless=new');
const chrome = spawn(CHROME, args, { stdio: 'ignore' });

let out;
try {
    let cdp = null;
    for (let i = 0; i < 60; i++) {
        try { cdp = await Cdp.connect(`http://127.0.0.1:${PORT}`); break; } catch { await sleep(250); }
    }
    if (!cdp) throw new Error('CDP never came up');
    const { sessionId } = await newPage(cdp);
    await goto(cdp, sessionId, PAGE);
    await sleep(400);
    out = JSON.parse(await evaluate(cdp, sessionId, PROBE));
    await cdp.close();
} finally {
    chrome.kill('SIGKILL');
    await fs.rm(tmp, { recursive: true, force: true });
}

const zig = `// GENERATED by tools/fingerprint/dump-css-current-color.mjs — do not hand-edit.
//
// Measured from ${out.ua}
// ${out.follows.length} of ${out.total} computed longhands follow the element's own \`color\`.
//
// Their initial value is \`currentcolor\`, so the one number
// chrome_initial_values.zig recorded for each of them is only right while the
// page leaves the text black. Measured by giving an element two different
// colours in turn and keeping the longhands that answered both.
//
// \`color\` itself is not here: it is the source rather than a follower.

const std = @import("std");

/// Longhands whose initial value is \`currentcolor\`.
pub const follows_color = std.StaticStringMap(void).initComptime(.{
${out.follows.map((n) => `    .{"${n}"},`).join('\n')}
});

/// True when \`name\`'s initial value is the element's own computed \`color\`.
pub fn followsColor(name: []const u8) bool {
    return follows_color.has(name);
}
`;

await fs.writeFile(outPath, zig);
console.error(`wrote ${outPath}: ${out.follows.length} of ${out.total} follow color`);
console.error(out.follows.join(' '));
