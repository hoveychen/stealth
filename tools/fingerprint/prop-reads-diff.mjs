#!/usr/bin/env node
// Reads a prop-reads.json and writes the run-expr probe that asks both engines
// for exactly those members -- no more, and in particular no less-visited ones
// picked because they were easy to think of.
//
// The point is to stop guessing which part of the surface to compare. A full
// descriptor sweep compares thousands of members and buries the handful the
// guard actually consulted; this narrows it to the ones a station's own
// collector reached, which for x-hyatt is 581 across 4 realms.
//
// Only the members reachable from a singleton are emitted: `Navigator.vendor`
// is `navigator.vendor` in any page, but `DOMRect.width` needs a rect and
// `CanvasRenderingContext2D.fillText` needs a call with arguments this log
// doesn't record. Those are named in the skipped tally rather than silently
// dropped -- what a run left out is part of its reading.
//
//   node tools/fingerprint/prop-reads-diff.mjs results/prop-reads-hyatt.json > /tmp/p.js
//   node tools/fingerprint/run-expr.mjs chrome     /tmp/p.js > results/pr-ch.json
//   node tools/fingerprint/run-expr.mjs lightpanda /tmp/p.js > results/pr-lp.json
//   node tools/fingerprint/expr-diff.mjs results/pr-ch.json results/pr-lp.json
import fs from 'node:fs';

const src = process.argv[2];
if (!src) {
    console.error('usage: prop-reads-diff.mjs <prop-reads.json>');
    process.exit(2);
}

// Interface -> the expression that yields its one instance in any document.
const SINGLETONS = {
    Window: 'window',
    Navigator: 'navigator',
    NavigatorUAData: 'navigator.userAgentData',
    NetworkInformation: 'navigator.connection',
    Screen: 'screen',
    ScreenOrientation: 'screen.orientation',
    Location: 'location',
    Document: 'document',
    Performance: 'performance',
    PerformanceTiming: 'performance.timing',
    MemoryInfo: 'performance.memory',
    History: 'history',
    VisualViewport: 'visualViewport',
    UserActivation: 'navigator.userActivation',
    PluginArray: 'navigator.plugins',
    MimeTypeArray: 'navigator.mimeTypes',
    StyleSheetList: 'document.styleSheets',
    BarProp: 'toolbar',
    Crypto: 'crypto',
    SpeechSynthesis: 'speechSynthesis',
    Keyboard: 'navigator.keyboard',
    StorageManager: 'navigator.storage',
};

const reads = JSON.parse(fs.readFileSync(src, 'utf8')).reads;
const cases = [];
const skipped = {};
const seen = new Set();
for (const r of reads) {
    const dot = r.property.indexOf('.');
    const iface = r.property.slice(0, dot);
    const member = r.property.slice(dot + 1);
    const root = SINGLETONS[iface];
    if (!root) {
        skipped[iface] = (skipped[iface] ?? 0) + 1;
        continue;
    }
    if (seen.has(r.property)) continue;
    seen.add(r.property);
    cases.push({ key: r.property, expr: `${root}.${member}`, hits: r.occurrences });
}
cases.sort((a, b) => b.hits - a.hits);

// A reading per member: the type, and a value flattened enough to compare
// across engines without dragging a live object through JSON. `typeof` alone
// misses a wrong number; the raw value alone turns every function into the
// same "function" string and hides which one.
const body = cases.map((c) => `  ${JSON.stringify(c.key)}: read(() => ${c.expr}),`).join('\n');
process.stdout.write(`// generated by prop-reads-diff.mjs from ${src}
// ${cases.length} members reachable from a singleton; skipped by interface:
// ${Object.entries(skipped).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}:${v}`).join(' ')}
(() => {
  const read = (f) => {
    try {
      const v = f();
      const t = typeof v;
      if (v === null) return { t: 'null' };
      if (t === 'function') return { t, name: v.name, len: v.length };
      if (t === 'object') {
        const tag = Object.prototype.toString.call(v);
        // A collection's size is a reading; its contents are a different probe.
        return { t, tag, len: typeof v.length === 'number' ? v.length : undefined };
      }
      if (t === 'number' && !Number.isFinite(v)) return { t, v: String(v) };
      return { t, v };
    } catch (e) {
      return { t: 'throw', v: String(e && e.message || e).slice(0, 120) };
    }
  };
  return JSON.stringify({
${body}
  });
})()
`);
