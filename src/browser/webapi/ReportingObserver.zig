// https://developer.mozilla.org/en-US/docs/Web/API/ReportingObserver
//
// The observer half of the Reporting API. A report is generated by the browser
// itself -- a deprecation, an intervention, a crash -- and this engine
// generates none, so an observer here never has anything to hand back and
// `takeRecords()` always answers an empty array. That matches a quiet Chrome
// tab: the single record Chrome produced while this was being measured was its
// own deprecation warning for XSLTProcessor, which is Chrome telling on itself.
//
// What *is* observable without any report existing is the constructor: the
// callback must be a function, and ReportingObserverOptions.types must be a
// sequence. Both messages below are Chrome's own. Measured on a headed
// Chrome 150 (probe-win29/win36).

const std = @import("std");
const lp = @import("lightpanda");

const js = @import("../js/js.zig");
const Page = @import("../Page.zig");
const dictionary = @import("dictionary.zig");

const Execution = js.Execution;

const ReportingObserver = @This();

const Reader = dictionary.Reader("ReportingObserver", "ReportingObserverOptions");

_rc: lp.RC = .{},
_arena: *lp.Arena,
_callback: js.Function.Global,
_buffered: bool = false,
_types: []const []const u8 = &.{},
_observing: bool = false,

pub fn constructor(callback: js.Value, options_: ?js.Value, exec: *const Execution) !*ReportingObserver {
    if (!callback.isFunction()) {
        return dictionary.throwTypeError(
            "Failed to construct 'ReportingObserver': parameter 1 is not of type 'Function'.",
            exec,
        );
    }

    const arena = try exec.getArena(.tiny, "ReportingObserver");
    errdefer arena.release();

    const init = try Reader.read(options_, exec);
    const types = try readTypes(init, arena.allocator(), exec);
    const buffered = try init.boolean("buffered", false);

    const self = try arena.create(ReportingObserver);
    self.* = .{
        ._arena = arena,
        ._callback = try callback.toZig(js.Function.Global),
        ._types = types,
        ._buffered = buffered,
    };
    return self;
}

/// `sequence<DOMString>?`. Chrome rejects anything non-iterable with its own
/// "cannot be converted to a sequence" wording rather than the generic
/// conversion failure, which is why this is read by hand.
fn readTypes(init: Reader, allocator: std.mem.Allocator, exec: *const Execution) ![]const []const u8 {
    const member = (try init.present("types")) orelse return &.{};
    if (member.isNull()) {
        return &.{};
    }
    if (!member.isArray()) {
        return Reader.notASequence("types", exec);
    }

    const array = member.toArray();
    const types = try allocator.alloc([]const u8, array.len());
    for (types, 0..) |*entry, i| {
        const value = try array.get(@intCast(i));
        entry.* = try value.toStringSliceWithAlloc(allocator);
    }
    return types;
}

pub fn deinit(self: *ReportingObserver, _: *Page) void {
    self._callback.release();
    self._arena.release();
}

pub fn acquireRef(self: *ReportingObserver) void {
    self._rc.acquire();
}

pub fn releaseRef(self: *ReportingObserver, page: *Page) void {
    self._rc.release(self, page);
}

pub fn observe(self: *ReportingObserver) void {
    self._observing = true;
}

pub fn disconnect(self: *ReportingObserver) void {
    self._observing = false;
}

/// Always empty: nothing here ever queues a report.
pub fn takeRecords(_: *ReportingObserver) []const js.Undefined {
    return &.{};
}

pub const JsApi = struct {
    pub const bridge = js.Bridge(ReportingObserver);

    pub const Meta = struct {
        pub const name = "ReportingObserver";
        pub const prototype_chain = bridge.prototypeChain();
        pub var class_id: bridge.ClassId = undefined;
    };

    pub const constructor = bridge.constructor(ReportingObserver.constructor, .{ .arity = 1 });

    pub const disconnect = bridge.function(ReportingObserver.disconnect, .{});
    pub const observe = bridge.function(ReportingObserver.observe, .{});
    pub const takeRecords = bridge.function(ReportingObserver.takeRecords, .{});
};

